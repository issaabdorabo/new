    fun translate(text: String): String {
        if (text.isBlank()) return text
        val exact = exactMap[text]
        if (exact != null) return exact

        val trimmed = text.trim()
        val trimmedExact = exactMap[trimmed]
        if (trimmedExact != null) {
            val leading = text.takeWhile { it.isWhitespace() }
            val trailing = text.takeLastWhile { it.isWhitespace() }
            return "$leading$trimmedExact$trailing"
        }

        // Check if there are Arabic characters
        var hasArabic = false
        for (ch in text) {
            if (ch in '\u0600'..'\u06FF') {
                hasArabic = true
                break
            }
        }
        if (!hasArabic) return text

        var result = text
        for ((ar, en) in tokenReplacements) {
            if (result.contains(ar)) {
                result = result.replace(ar, en)
            }
        }
        return result
    }
